/**
 * Dump every trilingual string the approved mock carries, grouped by section, in document
 * order — the working sheet for porting copy. Nothing here is inferred: it reads the
 * data-en / data-ru / data-th attributes the mock's own language switch uses.
 *   node scripts/od-strings.mjs > docs/design/opendesign/approved-strings.md
 */
import { readFileSync } from 'node:fs';

const od = readFileSync('docs/design/opendesign/tawanpower-landing-unified.html', 'utf8').replace(/\r\n/g, '\n');
const attr = (tag, name) => (tag.match(new RegExp(`${name}="([^"]*)"`)) || [, ''])[1];
const unesc = (s) => s.replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&')
  .replace(/&nbsp;/g, ' ').replace(/&rdquo;|&ldquo;/g, '"').replace(/&mdash;/g, '—').replace(/&times;/g, '×');

// Section boundaries, so each string is attributed to the band it appears in.
const bounds = [...od.matchAll(/data-od-id="(uni-[a-z]+)"/g)].map((m) => ({ at: m.index, id: m[1] }));
const sectionAt = (pos) => [...bounds].reverse().find((b) => b.at <= pos)?.id || '(outside sections)';

const rows = [];
for (const m of od.matchAll(/<([a-z0-9]+)\s[^>]*data-en="[^"]*"[^>]*>/gi)) {
  const tag = m[0];
  const en = unesc(attr(tag, 'data-en'));
  if (!en.trim()) continue;
  rows.push({
    at: m.index,
    tag: m[1],
    cls: attr(tag, 'class'),
    sec: sectionAt(m.index),
    en,
    ru: unesc(attr(tag, 'data-ru')),
    th: unesc(attr(tag, 'data-th')),
  });
}

let out = '# Approved strings — Open Design `tawanpower-landing-unified.html`\n\n' +
  'Generated by `node scripts/od-strings.mjs` from the frozen approved mock. ' +
  `${rows.length} trilingual strings.\n\n`;
let last = null;
for (const r of rows) {
  if (r.sec !== last) { out += `\n## ${r.sec}\n\n`; last = r.sec; }
  out += `- \`${r.tag}${r.cls ? '.' + r.cls.trim().split(/\s+/).join('.') : ''}\` — **en** ${r.en}` +
    (r.ru ? ` · **ru** ${r.ru}` : '') + (r.th ? ` · **th** ${r.th}` : '') + '\n';
}
console.log(out);
