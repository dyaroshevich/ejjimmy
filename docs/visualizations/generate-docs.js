const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '../..');
const docsDir = path.join(projectRoot, 'docs');
const outFile = path.join(__dirname, 'docs-data.js');

function walkDir(dir, results = {}) {
  if (!fs.existsSync(dir)) return results;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === '.next' || e.name === 'visualizations') continue;
      walkDir(full, results);
    } else if (e.name.endsWith('.md') || e.name.endsWith('.sql')) {
      try {
        const content = fs.readFileSync(full, 'utf-8');
        const rel = path.relative(projectRoot, full).replace(/\\/g, '/');
        // Key = just filename for short lookup, value has full path + content
        results[e.name] = { path: rel, content: content.slice(0, 8000) };
      } catch {}
    }
  }
  return results;
}

const data = {};
walkDir(projectRoot, data);
// Also walk docs subdirs specifically
walkDir(docsDir, data);

const js = `// Auto-generated by generate-docs.js — do not edit
window.DOCS_DATA = ${JSON.stringify(data, null, 0)};
`;

fs.writeFileSync(outFile, js, 'utf-8');
console.log(`Generated ${outFile} with ${Object.keys(data).length} files`);
