## แรงจูงใจด้านภาษีและการสนับสนุนจากภาครัฐ

### มาตรการลดหย่อนภาษี

ในปี 2026 รัฐบาลไทยยังคงมาตรการส่งเสริม:
- **ยกเว้นภาษีนำเข้า** สำหรับแผงโซลาร์เซลล์และอินเวอร์เตอร์ (มาตรการต่อเนื่อง)
- **ลดหย่อนภาษีเงินได้** สำหรับการลงทุนติดตั้ง (สูงสุด 3 ปี ในบางโครงการ)
- **สินเชื่อสีเขียว** จากธนาคารพาณิชย์ — อัตราดอกเบี้ยพิเศษ 3–5%

### โครงการ PEA และนโยบาย

- **Net Metering** — ยังอยู่ในช่วงทดลองในบางพื้นที่ แต่ในกระบี่อาจยังใช้ระบบ Net Billing ซึ่งขายไฟคืนได้ในราคารับซื้อต่ำ
- **คำแนะนำ**: การออกแบบระบบที่เน้น **Self-Consumption** (ใช้ไฟเองสูงสุด) จะคุ้มค่าที่สุดในปัจจุบัน

