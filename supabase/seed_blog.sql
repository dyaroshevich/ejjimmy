## ผลตอบแทนจากการลงทุน (ROI) — ตัวเลขที่คุณต้องรู้

### ระยะเวลาคืนทุน

ด้วยอัตราค่าไฟฟ้าของการไฟฟ้าส่วนภูมิภาค (PEA) ที่เฉลี่ย 4.7 บาทต่อหน่วยและปรับตัวสูงขึ้น 3–5% ทุกปี ระบบโซลาร์เซลล์สำหรับวิลล่าในกระบี่ให้ผลตอบแทนที่น่าสนใจ:

| ขนาดระบบ | ราคารวม (บาท) | ค่าไฟที่ประหยัดได้/ปี | ระยะเวลาคืนทุน | ROI 25 ปี |
|----------|--------------|-------------------|--------------|----------|
| 5 kW | 250,000–400,000 | 48,000–72,000 | 4–6 ปี | 400–600% |
| 10 kW | 500,000–800,000 | 96,000–144,000 | 4–5 ปี | 450–650% |
| 15 kW | 750,000–1,100,000 | 144,000–216,000 | 4–5 ปี | 500–700% |

หลังจากคืนทุนแล้ว คุณจะได้ไฟฟ้าฟรีไปอีกกว่า 20 ปี — เทียบได้กับเงินปันผล 20–30% ต่อปีจากการลงทุนครั้งเดียว

### เปรียบเทียบกับสินทรัพย์ลงทุนอื่น

| สินทรัพย์ | ผลตอบแทนเฉลี่ยต่อปี | ความเสี่ยง | สภาพคล่อง |
|-----------|-------------------|-----------|----------|
| โซลาร์เซลล์ (กระบี่) | 20–30% | ต่ำมาก | ปานกลาง |
| กองทุนรวม SET | 5–10% | ปานกลาง | สูง |
| บัญชีฝากประจำ | 1.5–2.5% | ต่ำ | สูง |
| ทองคำ | 5–12% | ปานกลาง-สูง | สูง |
| อสังหาริมทรัพย์ให้เช่า | 3–7% | ปานกลาง | ต่ำ |

### ปัจจัยที่ทำให้ ROI ของกระบี่สูงกว่าพื้นที่อื่น

1. **แสงแดดจัดตลอดปี** — กระบี่ได้รับรังสีแสงอาทิตย์สูงกว่าภาคเหนือ 15–20%
2. **ค่าไฟสูง** — อัตรา PEA ในกระบี่สูงกว่ากรุงเทพฯ ในบางช่วง
3. **ค่าติดตั้งแข่งขันได้** — ผู้รับเหมาในกระบี่มีต้นทุนการดำเนินงานต่ำกว่าภูเก็ต 10–15%
4. **ภาษีที่ดินและบ้าน** — บ้านที่มีโซลาร์เซลล์ได้รับการลดหย่อนในบางพื้นที่

