### ติดตั้งแล้วต้องแจ้ง PEA หรือไม่?

ใช่ ต้องแจ้งการไฟฟ้าส่วนภูมิภาค ผู้ติดตั้งที่มีประสบการณ์จะดำเนินการให้คุณเอง ใช้เวลา 1–2 สัปดาห์

### ถ้าฉันขายบ้าน ระบบโซลาร์เซลล์จะขายพร้อมบ้านหรือไม่?

