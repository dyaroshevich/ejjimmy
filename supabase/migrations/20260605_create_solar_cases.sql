CREATE TABLE IF NOT EXISTS public.solar_cases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR NOT NULL UNIQUE,
    customer_name VARCHAR,
    location_name VARCHAR,
    lat NUMERIC,
    lng NUMERIC,
    system_kw NUMERIC,
    roof_type VARCHAR,
    inverter_brand VARCHAR,
    panel_brand VARCHAR,
    savings_annual_thb NUMERIC,
    payback_years NUMERIC,
    case_description TEXT,
    customer_quote TEXT,
    media_assets JSONB DEFAULT '{}'::jsonb,
    metadata JSONB DEFAULT '{}'::jsonb,
    published BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

ALTER TABLE public.solar_cases ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read for published cases" ON public.solar_cases;
CREATE POLICY "Public read for published cases" ON public.solar_cases
    FOR SELECT USING (published = true);
