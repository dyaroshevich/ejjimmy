## ค่าใช้จ่ายแอบแฝงที่ต้องรู้ก่อนตัดสินใจ

ผู้รับเหมาบางรายเสนอราคาต่ำในช่วงแรก แต่เพิ่มค่าใช้จ่ายภายหลัง ถามล่วงหน้าเกี่ยวกับค่าใช้จ่ายเหล่านี้:

### 1. อัพเกรดตู้ไฟฟ้าหลัก (10,000–30,000 บาท)
หากบ้านของคุณใช้ตู้ไฟฟ้ารุ่นเก่า อาจต้องเปลี่ยนเพื่อรองรับระบบโซลาร์เซลล์ โดยเฉพาะบ้านที่สร้างเกิน 15 ปีแล้ว

### 2. การเสริมโครงสร้างหลังคา (20,000–50,000 บาท)
หลังคากระเบื้องหรือหลังคาเก่าอาจต้องเสริมโครงสร้างเพื่อรองรับน้ำหนักแผง วิศวกรควรตรวจสอบก่อนติดตั้ง

### 3. โมดูล 4G สำหรับตรวจสอบระยะไกล (5,000–10,000 บาท)
อินเวอร์เตอร์บางรุ่นต้องการ 4G dongle เพิ่มเติมสำหรับการเชื่อมต่ออินเทอร์เน็ต โดยเฉพาะในพื้นที่ที่ WiFi ไม่แรงพอ

### 4. การทำความสะอาดแผงประจำปี (5,000–8,000 บาท/ครั้ง)
ในกระบี่ที่มีฝุ่นเกลือและละอองทะเล ควรทำความสะอาด 2 ครั้ง/ปี ขอส่วนลดแพ็กเกจรายปีจากผู้ติดตั้ง

### 5. ค่าประกันระบบ (2,000–5,000 บาท/ปี)
แนะนำให้ทำประกันสำหรับความเสียหายจากฟ้าผ่า น้ำท่วม หรือสัตว์ต่างๆ โดยเฉพาะในกระบี่ที่มีฟ้าผ่าถี่

### ตารางสรุปค่าใช้จ่ายทั้งหมดสำหรับระบบ 5 kW

