## อะไรอยู่ในราคานั้นบ้าง?

ระบบโซลาร์เซลล์ครบวงจรในกระบี่ควรประกอบด้วย:

| รายการ | รายละเอียด | ราคาโดยประมาณ |
|--------|-----------|--------------|
| แผงโซลาร์เซลล์ | Tier-1 (Jinko, Longi, Canadian Solar, Trina) | 40–50% ของราคารวม |
| อินเวอร์เตอร์ | String หรือ Hybrid (Deye, Huawei, Growatt, GoodWe) | 10–15% ของราคารวม |
| โครงสร้างยึด | อลูมิเนียมหรือสแตนเลส สำหรับหลังคาหรือพื้นดิน | 5–10% |
| สายไฟและคอนเนคเตอร์ | MC4, PV Cable, AC Cable | 3–5% |
| ตู้ไฟฟ้า AC | เบรกเกอร์, อุปกรณ์ป้องกันไฟกระชาก, มิเตอร์ | 3–5% |
| ค่าแรงติดตั้ง | 1–3 วัน ขึ้นอยู่กับขนาดระบบ | 8–12% |
| ดำเนินการ PEA | แจ้งการไฟฟ้าส่วนภูมิภาค | 1–3% |
| รับประกัน | แผง 10–12 ปี, ผลผลิต 25 ปี, อินเวอร์เตอร์ 5–10 ปี | รวมในราคา |

