## คำถามที่พบบ่อย

### ระบบโซลาร์เซลล์ติดตั้งนานไหมในกระบี่?

การติดตั้งที่อยู่อาศัยใช้เวลา 1–3 วัน เอกสารและการแจ้ง PEA เพิ่มอีก 1–2 สัปดาห์ รวมทั้งกระบวนการประมาณ 2–3 สัปดาห์นับจากเซ็นสัญญา

### แผงโซลาร์เซลล์เพิ่มมูลค่าบ้านในกระบี่ไหม?

ใช่ บ้านที่มีโซลาร์เซลล์ขายได้เร็วและราคาสูงกว่า 3–5% ในประเทศไทย โดยเฉพาะในกลุ่มวิลล่าสำหรับชาวต่างชาติที่ใส่ใจสิ่งแวดล้อม

### รับประกันอะไรบ้าง?

- แผง Tier-1: รับประกันผลผลิต 25 ปี (80% ที่ปีที่ 25)
- อินเวอร์เตอร์: 5–10 ปี ขึ้นอยู่กับแบรนด์ (ต่ออายุได้)
- งานติดตั้ง: 1–2 ปี
- แบตเตอรี่ LiFePO4: 8–10 ปี

### แผงทำงานในช่วงหน้าฝนกระบี่ไหม?

ใช่ แต่ผลผลิตลดลง 30–50% ในช่วงมรสุม ระบบถูกออกแบบสำหรับการผลิตทั้งปี คุณยังประหยัดเงินโดยรวมได้มาก

### ต้องเปลี่ยนแผงใหม่เมื่อไหร่?

แผง Tier-1 คุณภาพสูงอายุ 25–30 ปี ไม่ต้องเปลี่ยนเป็นเวลา 25 ปี การเปลี่ยนคือเพื่อเพิ่มประสิทธิภาพหรือขยายระบบ ไม่ใช่เพราะแผงเสีย

