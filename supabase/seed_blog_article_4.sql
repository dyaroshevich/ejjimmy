## การตรวจสอบระบบ — จับปัญหาตั้งแต่เนิ่นๆ

ระบบโซลาร์เซลล์สมัยใหม่ทุกระบบมีระบบตรวจสอบ — ผ่าน WiFi, Ethernet หรือ 4G dongle นี่คือเครื่องมือบำรุงรักษาที่ทรงพลังที่สุดของคุณ

### สิ่งที่ควรตรวจสอบ

- **ผลผลิตรายวัน** — เปรียบเทียบกับวันเดียวกันของสัปดาห์ก่อน การลดลงกะทันหันมักบ่งบอกปัญหา
- **กำลังผลิตสูงสุด** — ควรใกล้เคียงพิกัดระบบ (เช่น ระบบ 5 kW ควรผลิตใกล้ 5 kW ในวันที่แดดจัด)
- **แรงดันไฟฟ้าของ String** — แต่ละสายของแผงควรมีแรงดันใกล้เคียงกัน สายที่มีแรงดันต่ำกว่ามากอาจมีแผงเสียหรือการเชื่อมต่อหลวม
- **อุณหภูมิ** — อินเวอร์เตอร์ที่ร้อนกว่าปกติอาจมีปัญหาการระบายความร้อน
- **การชาร์จแบตเตอรี่** — ตรวจสอบรอบการชาร์จและความจุที่เหลืออยู่

### การแจ้งเตือนอัตโนมัติ

แอปพลิเคชันตรวจสอบส่วนใหญ่ให้คุณตั้งค่าการแจ้งเตือน:
- ส่งทาง **LINE** หรือ **อีเมล** เมื่อเกิด Fault
- แจ้งเตือนเมื่อผลผลิตต่ำกว่าเกณฑ์ที่กำหนด
- แจ้งเตือนเมื่อแบตเตอรี่มีปัญหา

> ระบบของ Tawan Power ทุกระบบมีการติดตั้งระบบตรวจสอบฟรี พร้อมตัวเลือกการตรวจสอบระยะไกล 24/7 โดยทีมวิศวกรของเรา

