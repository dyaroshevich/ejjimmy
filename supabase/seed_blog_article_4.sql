## การดูแลอินเวอร์เตอร์ — ชิ้นส่วนที่สำคัญที่สุด

อินเวอร์เตอร์เป็นชิ้นส่วนที่อ่อนไหวที่สุดและมีโอกาสเสียมากที่สุด ไม่เหมือนแผง อินเวอร์เตอร์มีชิ้นส่วนอิเล็กทรอนิกส์ที่เสื่อมสภาพตามเวลา โดยเฉพาะในสภาพอากาศร้อนของกระบี่

### Checklist การดูแลอินเวอร์เตอร์

- ✅ **ระบายอากาศดีเสมอ** — ตรวจสอบว่าพัดลมระบายความร้อนไม่มีอะไรปิดกั้น อินเวอร์เตอร์ที่ติดตั้งในที่แดดส่องหรือที่อับจะเสื่อมเร็วกว่า
- ✅ **ตรวจสอบหน้าจอทุกสัปดาห์** — มองหารหัสข้อผิดพลาด ไฟกระพริบแปลกๆ หรือข้อความ "Grid Fault"
- ✅ **ทำความสะอาดช่องระบายอากาศ** — ฝุ่นและแมลงเล็กๆ สามารถอุดตันช่องระบายอากาศได้ ใช้แปรงขนนุ่มหรือลมเป่าทุก 3 เดือน
- ✅ **ตรวจสอบผ่านแอปพลิเคชัน** — อินเวอร์เตอร์สมัยใหม่ (Deye, Huawei, Growatt) มีแอปที่แจ้งเตือนเมื่อเกิดปัญหา ควรเปิดเช็คอย่างน้อยสัปดาห์ละครั้ง
- ✅ **ฟังเสียงผิดปกติ** — เสียงฮัม เสียงคลิก หรือเสียงพัดลมที่เปลี่ยนไป อาจบ่งบอกปัญหา

