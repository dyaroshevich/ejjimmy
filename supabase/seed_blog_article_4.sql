## ปัญหาที่พบบ่อยในกระบี่

### การกัดกร่อนจากเกลือทะเล

ละอองเกลือเร่งการกัดกร่อนของคอนเนคเตอร์ อุปกรณ์ยึด และแม้แต่กรอบแผง

**อาการ:** คราบสีเขียว/ขาวบนชิ้นส่วนโลหะ, คอนเนคเตอร์เปลี่ยนสี, ผลผลิตลดลง

**วิธีป้องกันและแก้ไข:**
- ใช้อุปกรณ์ Stainless Steel เกรดทะเล (Marine Grade)
- ล้างแผงด้วยน้ำสะอาดบ่อยขึ้น — ทุกเดือนถ้าอยู่ในระยะ 1 กม. จากทะเล
- ใช้อุปกรณ์กันน้ำระดับ IP65 ขึ้นไป
- ตรวจสอบและเปลี่ยนคอนเนคเตอร์ที่เริ่มเป็นสนิม

### นกทำรังใต้แผง

นกชอบร่มเงาใต้แผงที่ยกสูง วัสดุทำรังขัดขวางการระบายอากาศ สร้างความร้อนสะสม และเสี่ยงไฟไหม้จากเศษวัสดุแห้งใกล้การเชื่อมต่อไฟฟ้า

**วิธีป้องกัน:**
- ติดตั้งตาข่ายกันนก (5,000–15,000 บาท)
- ติดตั้งตั้งแต่แรกดีกว่า — ราคาถูกกว่าการติดตั้งทีหลัง
- ตรวจสอบใต้แผงปีละครั้งในช่วงนกทำรัง

### กิ้งก่าและสัตว์เลื้อยคลาน

ใช่ ปัญหาจริงในกระบี่! กิ้งก่าหรือตะกวดที่ปีนบนแผงที่ติดตั้งบนพื้นอาจทำให้กระจกเป็นรอยหรือเสียหาย

**วิธีป้องกัน:**
- ระบบที่ติดตั้งบนพื้นควรมีรั้วต่ำกั้น
- ใช้ท่อร้อยสายไฟแบบแข็ง (ไม่ใช่ท่อ PVC อ่อน)
- สัตว์แทะสายไฟ — ใช้ลวดตาข่ายครอบท่อ

### ฟ้าผ่า

กระบี่มีความหนาแน่นฟ้าผ่าสูงที่สุดแห่งหนึ่งในประเทศไทย ฟ้าผ่าใกล้เคียงสามารถเหนี่ยวนำแรงดันไฟกระชากที่ทำลายอินเวอร์เตอร์ แม้ไม่โดนโดยตรง

**วิธีป้องกัน:**
- ระบบต้องมี Surge Protection Device (SPD) Type 1 หรือ Type 2 ทั้งฝั่ง DC และ AC
- การต่อสายดินที่ได้มาตรฐาน
**หมายเหตุ:** อุปกรณ์ป้องกันนี้เป็นมาตรฐานในการติดตั้งของ Tawan Power ทุกระบบ

