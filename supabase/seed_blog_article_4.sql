## ทำความสะอาดด้วยตัวเอง: ขั้นตอนปลอดภัย

คุณสามารถทำความสะอาดแผงด้วยตัวเองได้ถ้าแผงอยู่บนพื้นดินหรือหลังคาเตี้ยที่เดินถึงได้ สำหรับหลังคาสูงหรือหลังคาลาดชัน ควรจ้างมืออาชีพ

### อุปกรณ์ที่ต้องใช้

| อุปกรณ์ | ราคาโดยประมาณ | หาซื้อได้ที่ |
|---------|--------------|-----------|
| แปรงขนนุ่มพร้อมด้ามต่อ | 500–1,500 บาท | HomePro, Thai Watsadu |
| น้ำสะอาด (ควรใช้น้ำ DI) | 20–50 บาท/ครั้ง | ร้านขายน้ำสะอาดทั่วไป |
| ที่ปัดน้ำยาง | 200–500 บาท | HomePro, ไทวัสดุ |
| สบู่เหลวอ่อน (ไม่จำเป็น) | 20–50 บาท | ทุกร้าน |

### ขั้นตอนการทำความสะอาด

1. **เช็คหน้าจออินเวอร์เตอร์ก่อน** — จดบันทึกการผลิตวันนี้เพื่อเปรียบเทียบหลังทำความสะอาด
2. **เลือกเวลาที่เหมาะสม** — เช้าตรู่หรือบ่ายแก่ๆ ตอนแผงเย็น การทำความสะอาดแผงร้อนอาจทำให้เกิด Thermal Shock และรอยร้าวขนาดเล็ก
3. **ฉีดน้ำล้าง** — กำจัดฝุ่นและเศษสิ่งสกปรกหลวมๆ
4. **ขัดเบาๆ** — ใช้แปรงขนนุ่มกับน้ำสบู่สำหรับคราบฝังแน่น (มูลนก โคลนแห้ง)
5. **ล้างออกให้สะอาด** — กำจัดคราบสบู่ทั้งหมด
6. **เช็ดด้วยที่ปัดน้ำ** — ป้องกันคราบน้ำที่สร้างเงาบนแผง
7. **เช็คอินเวอร์เตอร์อีกครั้ง** — ยืนยันว่าการผลิตเพิ่มขึ้น

### ข้อควรระวัง

- **ห้ามใช้น้ำยาทำความสะอาดที่มีฤทธิ์เป็นด่างหรือกรด** — น้ำยาล้างจานเจือจางใช้ได้ สารฟอกขาว น้ำยาทำความสะอาดห้องน้ำ หรือน้ำยาขัดสี จะทำให้แผงเสียหาย
- **ห้ามใช้เครื่องฉีดน้ำแรงดันสูง** — แรงดันน้ำอาจทำลายซีลและทำให้ Moisture เข้าแผง
- **ห้ามเดินบนแผงเด็ดขาด** — รอยร้าวขนาดเล็กทำให้น้ำเข้าและไฟรั่วได้

