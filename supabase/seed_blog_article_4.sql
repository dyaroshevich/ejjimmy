## คำถามที่พบบ่อย

### ฝนช่วยทำความสะอาดแผงโซลาร์เซลล์ได้ไหม?

**ได้บางส่วน** ฝนตกปรอยๆ ไม่ได้ช่วยอะไรเลย ฝนมรสุมหนักช่วยล้างฝุ่นหลวมๆ แต่ไม่สามารถขจัดมูลนก คราบเกลือ หรือโคลนแห้งได้ คุณยังต้องทำความสะอาดด้วยมือปีละ 2–4 ครั้ง

### เดินบนแผงโซลาร์เซลล์เพื่อทำความสะอาดได้ไหม?

**ไม่ได้เด็ดขาด** การเดินบนแผงทำให้เกิดรอยร้าวขนาดเล็กที่มองไม่เห็นด้วยตาเปล่า ลดประสิทธิภาพและทำให้การรับประกันเป็นโมฆะ ใช้แปรงด้ามยาวจากขอบหลังคา หรือจ้างมืออาชีพที่มีอุปกรณ์ความปลอดภัย

### แผงโซลาร์เซลล์อายุการใช้งานกี่ปีในสภาพอากาศไทย?

แผง Tier-1 (Jinko, Longi, Trina, Canadian Solar) มีอายุ 25–30 ปี สภาพอากาศร้อนและชื้นเร่งการเสื่อมสภาพเล็กน้อย — คาดการณ์การเสื่อม 0.5–0.7% ต่อปี แทนที่จะเป็น 0.4–0.5% มาตรฐาน หลัง 25 ปี แผงจะยังผลิตไฟได้ 80–85% ของวันแรก

### การรับประกันครอบคลุมปัญหาการดูแลรักษาหรือไม่?

- **รับประกันผลิตภัณฑ์:** ครอบคลุมข้อบกพร่องจากการผลิต (10–12 ปี)
- **รับประกันผลผลิต:** รับประกันกำลังผลิต (25 ปี ที่ 80%+)
- **ไม่ครอบคลุม:** การทำความสะอาด ความเสียหายจากพายุ หรือความเสียหายจากสัตว์
นี่คือเหตุผลที่การดูแลรักษาและประกันมีความสำคัญ

### Tawan Power มีแพ็กเกจบำรุงรักษาหรือไม่?

**มี** เรามีแผนบำรุงรักษาประจำปีเริ่มต้นที่ 3,500 บาท/ปีสำหรับระบบที่อยู่อาศัย รวม:
- ทำความสะอาดแผง 2 ครั้ง/ปี
- ตรวจเช็คระบบ 1 ครั้ง/ปี
- บริการตอบสนองด่วน (Priority Response)

ให้บริการสำหรับทุกระบบที่เราติดตั้ง และระบบจากผู้ติดตั้งรายอื่นด้วย

