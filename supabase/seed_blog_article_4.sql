## ทำไมแผงโซลาร์เซลล์ถึงต้องทำความสะอาดในกระบี่

กระบี่มีสามฤดู แต่ละฤดูมีความท้าทายต่อแผงโซลาร์เซลล์ที่แตกต่างกัน:

| ฤดู | เดือน | ความท้าทาย | ผลกระทบ |
|-----|-------|-----------|---------|
| ร้อน | มี.ค.–พ.ค. | ฝุ่นและเกสรดอกไม้ แผงสกปรกภายใน 2–3 สัปดาห์ | ผลผลิตลดลง 15–25% |
| ฝน | มิ.ย.–ต.ค. | ฝนช่วยล้างแผง แต่วันที่มีเมฆมากหมายถึงทุกวัตต์สำคัญ ผลึกเกลือสะสมบนแผงชายฝั่ง | ผลผลิตลดลง 30–50% (จากเมฆ) |
| เย็น | พ.ย.–ก.พ. | มูลนกจากนกอพยพ หน้าหนาวเป็นช่วงผลิตดีที่สุด | แผงสะอาด = ผลผลิตสูงสุด |

**ผลการศึกษาจากกรมพัฒนาพลังงานทดแทน** พบว่าแผงที่ไม่ทำความสะอาดในพื้นที่ชายฝั่งสูญเสียผลผลิตเฉลี่ย 18% เมื่อเทียบกับแผงที่ทำความสะอาดสม่ำเสมอ บางพื้นที่ใกล้ก่อสร้างสูญเสียมากถึง 30%

