## Hybrid (ไฮบริด) — ดีที่สุดของทั้งสองโลก

### ทำงานอย่างไร

ระบบ Hybrid เชื่อมต่อกับ PEA และมีแบตเตอรี่สำรอง อินเวอร์เตอร์จะสลับระหว่างพลังงานแสงอาทิตย์ แบตเตอรี่ และไฟฟ้าจาก PEA อย่างชาญฉลาดโดยอัตโนมัติ

### ข้อดี

- **สำรองไฟเมื่อไฟดับ** — จำเป็นสำหรับวิลล่าหรูที่มีระบบรักษาความปลอดภัย ตู้เย็น และแอร์
- **ใช้ไฟฟ้าตัวเองสูงสุด** — เก็บไฟฟ้าส่วนเกินในแบตเตอรี่แทนที่จะปล่อยทิ้ง
- **ใช้ไฟช่วง Peak ได้อย่างชาญฉลาด** — ชาร์จแบตเตอรี่ตอนกลางวัน ใช้ตอนกลางคืน
- **พร้อมสำหรับอนาคต** — เพิ่มแบตเตอรี่ตอนนี้หรือทีหลังก็ได้

### เทคโนโลยีเด่น: การสลับไฟภายใน 10ms

หัวใจของระบบ Hybrid คือ **ATS (Automatic Transfer Switch)** ที่ทำงานภายใน 10 มิลลิวินาที เร็วจนไฟในบ้านไม่กระพริบด้วยซ้ำ นี่คือความแตกต่างระหว่างระบบไฮบริดรุ่นใหม่กับระบบสำรองไฟแบบเก่า

### การทำงานอัจฉริยะ

```text
กลางวัน: แผง → บ้าน → แบตเตอรี่ (ส่วนเกิน)
กลางคืน: แบตเตอรี่ → บ้าน
ไฟดับ: แบตเตอรี่ → บ้าน (ภายใน 10ms)
แบตหมด: PEA → บ้าน (อัตโนมัติ)
```

### ข้อเสีย

- **ราคาสูงกว่า** — 40,000–100,000 บาทสำหรับอินเวอร์เตอร์ (ไม่รวมแบตเตอรี่)
- **แบตเตอรี่ LiFePO4 เพิ่ม 100,000–200,000 บาทสำหรับ 10 kWh**
- **ประสิทธิภาพต่ำกว่า On-Grid เล็กน้อย** (95–97%)

### เหมาะกับ

เจ้าของวิลล่า ผู้อยู่อาศัยที่เป็นชาวต่างชาติ และธุรกิจที่ไม่สามารถหยุดชะงักได้ หากคุณมีไฟดับบ่อยหรือต้องการความมั่นคงด้านพลังงาน ระบบไฮบริดที่มีแบตเตอรี่ 5–10 kWh คือจุดที่คุ้มค่าที่สุด

