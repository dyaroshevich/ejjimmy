## Off-Grid (Standalone) — อิสระจากสายส่ง

### ทำงานอย่างไร

ระบบ Off-Grid เป็นระบบที่พึ่งพาตนเองได้อย่างสมบูรณ์ แผงโซลาร์ชาร์จแบตเตอรี่ และอินเวอร์เตอร์ดึงไฟจากแบตเตอรี่มาใช้ในบ้าน ไม่มีการเชื่อมต่อกับ PEA เลย

### ข้อดี

- **อิสระด้านพลังงานอย่างสมบูรณ์** — ไม่พึ่งพาใคร
- **ทำงานได้ทุกที่** — เหมาะกับพื้นที่ห่างไกล เกาะ ไร่เลย์ เขาหลวง
- **ไม่ต้องมีเอกสาร PEA**

### ข้อเสีย

- **ราคาสูงมาก** — 80,000–150,000 บาทสำหรับอินเวอร์เตอร์ + แบตเตอรี่ 100,000–300,000 บาท
- **ถูกจำกัดด้วยความจุแบตเตอรี่** — ถ้าแบตหมดในวันที่ฝนตก คุณจะไม่มีไฟฟ้าใช้
- **แบตเตอรี่ต้องเปลี่ยนทุก 5–10 ปี**
- **ประสิทธิภาพต่ำกว่า** (90–95%) เนื่องจากการสูญเสียจากการชาร์จและคายประจุ

### เหมาะกับ

วิลล่าห่างไกล บ้านบนเกาะ ฟาร์ม หรือผู้ที่สร้างบ้านในพื้นที่ที่ไม่มีสายไฟ PEA เข้าถึง ไม่แนะนำสำหรับเจ้าของบ้านส่วนใหญ่ในกระบี่

