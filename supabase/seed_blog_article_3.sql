## คำถามที่พบบ่อย

### เพิ่มแบตเตอรี่เข้าระบบ On-Grid ทีหลังได้ไหม?

**ไม่ได้** ถ้าคุณซื้ออินเวอร์เตอร์ On-Grid ตั้งแต่แรก อินเวอร์เตอร์ On-Grid ไม่สามารถรับแบตเตอรี่ได้ คำแนะนำ: จ่ายเพิ่มอีกนิดตอนแรกเพื่อซื้อ Hybrid inverter แม้จะยังไม่ซื้อแบตเตอรี่ในตอนนี้ จะช่วยประหยัดค่าอัพเกรดในอนาคต

### อินเวอร์เตอร์มีอายุการใช้งานกี่ปี?

โดยทั่วไป 10–15 ปี แบรนด์ส่วนใหญ่รับประกัน 5–10 ปี ต่ออายุได้ คุณจะต้องเปลี่ยนอินเวอร์เตอร์ 1 ครั้งในช่วง 25 ปีของแผงโซลาร์เซลล์

### อินเวอร์เตอร์ต้องได้รับการรับรองจากไทยไหม?

ใช่ สำหรับการเชื่อมต่อกับ PEA จำเป็นต้องใช้อุปกรณ์ที่ได้รับการรับรองตามมาตรฐานของไทย แบรนด์หลักที่ขายผ่านตัวแทนจำหน่ายในไทยผ่านการรับรองแล้ว อินเวอร์เตอร์ราคาถูกจาก Shopee/Lazada ที่นำเข้าส่วนตัวอาจไม่ผ่านการรับรอง

### อินเวอร์เตอร์ Hybrid สามารถใช้โดยไม่มีแบตเตอรี่ได้ไหม?

ได้ อินเวอร์เตอร์ Hybrid หลายรุ่นสามารถทำงานเป็น On-Grid ก่อน แล้วค่อยเพิ่มแบตเตอรี่ทีหลัง นี่คือเหตุผลที่เราแนะนำให้เลือก Hybrid แม้คุณจะไม่ซื้อแบตเตอรี่ในวันแรก

