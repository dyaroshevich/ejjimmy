## On-Grid (Grid-Tied) — เชื่อมต่อสายส่ง

### ทำงานอย่างไร

ระบบ On-Grid เชื่อมต่อโดยตรงกับสายส่งของการไฟฟ้าส่วนภูมิภาค (PEA) เมื่อแดดส่อง คุณใช้ไฟฟ้าจากแผง เมื่อไม่มีแดดหรือกลางคืน คุณดึงไฟจาก PEA

### ข้อดี

- **ราคาถูกที่สุด** — 20,000–50,000 บาทสำหรับระบบ 5 kW
- **ประสิทธิภาพสูงสุด** — 97–98%
- **ติดตั้งและบำรุงรักษาง่าย**
- **ไม่ต้องใช้แบตเตอรี่** — ลดต้นทุนเริ่มต้น

### ข้อเสีย

- **ไม่มีไฟสำรองเมื่อไฟดับ** — ด้วยเหตุผลด้านความปลอดภัย อินเวอร์เตอร์ On-Grid จะหยุดทำงานเมื่อ PEA ดับเช่นกัน คุณจะไม่มีไฟฟ้าใช้แม้แดดจะแรง
- **ไม่สามารถเก็บพลังงาน** — ไฟฟ้าส่วนเกินจะถูกส่งเข้าสายส่ง โดยปกติไม่ได้รับค่าตอบแทนในประเทศไทย

### แผนภาพการทำงาน

```text
แผงโซลาร์ → อินเวอร์เตอร์ On-Grid → บ้าน → PEA
                                    ↘ ถ้าเกิน → ส่งคืน PEA (ไม่คิดเงิน)
```

### เหมาะกับ

บ้านในพื้นที่ที่ไฟฟ้าไม่เคยดับ (ส่วนใหญ่ในตัวเมืองกระบี่, Ao Nang) หากคุณไม่เคยมีปัญหาไฟดับและต้องการต้นทุนเริ่มต้นต่ำที่สุด นี่คือคำตอบ

| ระบบ On-Grid ขนาด 5 kW | ราคา |
|------------------------|------|
| ค่าอินเวอร์เตอร์ | 25,000–40,000 บาท |
| แผง + โครงสร้าง + สายไฟ | 150,000–200,000 บาท |
| ค่าติดตั้ง | 30,000–50,000 บาท |
| ดำเนินการ PEA | 5,000–10,000 บาท |
| **รวม** | **250,000–350,000 บาท** |

