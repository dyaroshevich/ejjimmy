## เลือกอินเวอร์เตอร์แบบไหน?

### แนวทางตัดสินใจอย่างง่าย

| ถ้าคุณ... | เลือก... | เพราะ... |
|-----------|---------|---------|
| งบประมาณจำกัด + ไฟฟ้าไม่เคยดับ | On-Grid | ถูกที่สุด คืนทุนเร็วที่สุด |
| ไฟดับบ่อย + ต้องการสำรอง | Hybrid | มีไฟใช้แม้ไฟดับ คุ้มค่าสุด |
| ไม่มีไฟฟ้าจาก PEA | Off-Grid | ต้องพึ่งพาตัวเองเท่านั้น |
| กำลังสร้างวิลล่าหรูใหม่ | Hybrid (Deye หรือ Sigenergy) | เตรียมพร้อมสำหรับอนาคต |
| ต้องการ EV Charger | Hybrid ที่รองรับ | Sigenergy หรือ Deye มีรุ่นรองรับ |
| งบประมาณจำกัดแต่ต้องการสำรอง | Hybrid (Growatt) | Hybrid ในราคาย่อมเยา |

### คำแนะนำพิเศษสำหรับกระบี่

กระบี่มี **ฟ้าผ่าถี่** ในช่วงมรสุม ดังนั้นทุกระบบควรมี:
- **อุปกรณ์ป้องกันไฟกระชาก (SPD)** ทั้งฝั่ง DC และ AC
- **สายดินคุณภาพสูง**
- **ระบบตรวจสอบระยะไกล** เพื่อแจ้งเตือนเมื่อเกิดปัญหา

